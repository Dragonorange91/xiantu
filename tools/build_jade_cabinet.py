"""Build the 2x2 jade cabinet through the installed desktop Blockbench MCP."""
import json
from blockbench_bridge import Bridge
from build_building_openings_blockbench import MODELS,texture,cuboid,runtime_export,save_export
from generate_building_material_resources import ROOT,ASSETS,DATA,TEXTURES,write_json,block_loot,merge_tag,recipe

def boxes(opened=False):
    result=[]
    def add(name,lo,hi,tex='smooth'): result.append((name,lo,hi,tex))
    # Four raised feet: the old solid plinth erased the antique silhouette.
    for x in (4,25):
        for z in (3,11):add(f'foot_{x}_{z}',[x,0,z],[x+3,5,z+3],'carved')
    add('base_rail',[3,4,2],[29,5.5,15],'carved')
    # Stepped scalloped apron leaves a genuine open gap below the cabinet.
    for x0,x1,y in ((6,10,2.5),(10,14,3),(14,18,3.5),(18,22,3),(22,26,2.5)):
        add('apron_'+str(x0),[x0,y,2],[x1,4,3],'carved')
    add('back',[4,5.5,13],[28,29,14])
    for x in (3,27):add('side_'+str(x),[x,5.5,3],[x+2,29,14])
    add('drawer_center',[15.5,5.5,2],[16.5,13.5,13],'carved')
    for y in (5.5,9,12.5):add('drawer_rail_'+str(y),[5,y,2],[27,y+1,13],'carved')
    for col,(x0,x1) in enumerate(((5,15.5),(16.5,27))):
        for row,y in enumerate((6.5,10)):
            add(f'drawer_{col}_{row}',[x0+.25,y+.15,2],[x1-.25,y+2.35,12])
            add(f'drawer_panel_{col}_{row}',[x0+1,y+.5,1.75],[x1-1,y+2,2],'carved')
            cx=(x0+x1)/2
            add(f'drawer_handle_{col}_{row}',[cx-.75,y+.8,1],[cx+.75,y+1.6,1.75],'carved')
    # Tall double doors with recessed carved panels, opening about outer hinges.
    add('door_bottom_rail',[5,13.5,2],[27,14.5,13],'carved')
    add('door_top_rail',[5,28,2],[27,29,13],'carved')
    add('interior_shelf',[5,20,3],[27,21,13])
    for col,(x0,x1) in enumerate(((5,15.75),(16.25,27))):
        door=[]
        def leaf(n,a,b,t='smooth'):door.append((f'door_{col}_{n}',a,b,t))
        leaf('panel',[x0+.75,15.25,2.5],[x1-.75,27.25,3.25],'carved')
        for x in (x0,x1-.75):leaf('stile_'+str(x),[x,14.5,1.75],[x+.75,28,3.5])
        for y in (14.5,27.25):leaf('rail_'+str(y),[x0+.75,y,1.75],[x1-.75,y+.75,3.5])
        hx=x1-1.75 if col==0 else x0+1
        leaf('handle',[hx,20,1],[hx+.75,22.5,1.75],'carved')
        for n,a,b,t in door:
            if opened:
                # Exact 90-degree rigid transform; no Java element rotation needed.
                hinge=x0 if col==0 else x1
                if col==0:
                    a,b=[hinge+2.5-b[2],a[1],2.5+ a[0]-hinge],[hinge+2.5-a[2],b[1],2.5+b[0]-hinge]
                else:
                    a,b=[hinge+a[2]-2.5,a[1],2.5+hinge-b[0]],[hinge+b[2]-2.5,b[1],2.5+hinge-a[0]]
                # Door wings swing toward the viewer (negative Z).
                a[2],b[2]=5-b[2],5-a[2]
            add(n,a,b,t)
    # Projecting Chinese cornice: center low, stepped upswept tips, not a flat lid.
    add('cornice_lower',[2,29,1],[30,30,15],'carved')
    add('cornice_middle',[1,30,.5],[31,30.75,15.5])
    add('crown_center',[4,30.75,1],[28,31.25,15],'carved')
    for x0,x1,y in ((1,4,31.25),(28,31,31.25),(0,2,31.75),(30,32,31.75)):
        add('upswept_tip_'+str(x0),[x0,30.75,.5],[x1,y+.25,15.5],'carved')
    return result

def uv(lo,hi):
    d=[hi[i]-lo[i] for i in range(3)]
    return {f:[0,0,d[a],d[b]] for f,a,b in [('north',0,1),('south',0,1),('east',2,1),('west',2,1),('up',0,2),('down',0,2)]}

def clipped(part,opened):
    x=(1-part%2)*16;y=part//2*16
    result=[]
    for name,a,z,tex in boxes(opened):
        lo=[max(a[0],x)-x,max(a[1],y)-y,a[2]]
        hi=[min(z[0],x+16)-x,min(z[1],y+16)-y,z[2]]
        if lo[0]<hi[0] and lo[1]<hi[1]:result.append((name,lo,hi,tex))
    return result

def collision_source():
    # Generated from the same geometry plan, cached once rather than unioned per query.
    lines=['package com.longju.xiantu.building;',
           'import net.minecraft.world.level.block.Block;',
           'import net.minecraft.world.phys.shapes.*;',
           '/** Generated by tools/build_jade_cabinet.py; antique cabinet geometry. */',
           'final class JadeCabinetShapes {',
           '    static final VoxelShape[][] SHAPES = create();',
           '    private static VoxelShape[][] create() {',
           '        VoxelShape[][] result = new VoxelShape[8][4];']
    for opened in (False,True):
        for part in range(4):
            args=',\n'.join('            new double[]{'+','.join(str(v) for v in a+b)+'}' for _,a,b,_ in clipped(part,opened))
            lines.append(f'        double[][] b{part+4*opened} = {{\n{args}\n        }};')
            lines.append(f'        result[{part+4*opened}] = rotated(b{part+4*opened});')
    lines += ['        return result;', '    }',
              '    private static VoxelShape[] rotated(double[][] boxes) {',
              '        VoxelShape[] result = new VoxelShape[4];',
              '        for (int turn=0;turn<4;turn++) {',
              '            VoxelShape shape=Shapes.empty();',
              '            for(double[] original:boxes) {',
              '                double[] b=original;',
              '                for(int t=0;t<turn;t++) b=new double[]{16-b[5],b[1],b[0],16-b[2],b[4],b[3]};',
              '                shape=Shapes.or(shape,Block.box(b[0],b[1],b[2],b[3],b[4],b[5]));',
              '            }', '            result[turn]=shape.optimize();',
              '        }', '        return result;', '    }','}']
    (ROOT/'src/main/java/com/longju/xiantu/building/JadeCabinetShapes.java').write_text('\n'.join(lines)+'\n',encoding='utf-8')

def main():
    collision_source()
    b=Bridge();b.request('tools/list',{});b.call('get_project_info')
    assert any(c['id']=='java_block' and c['has_compile'] for c in b.value(b.call('list_export_formats'))['codecs'])
    save_export(b,'project',MODELS/'before-antique-jade-cabinet.bbmodel')
    variants={};counts=[]
    refs=['xiantu:block/cloud_jade_smooth','xiantu:block/cloud_jade_carved']
    def project(name,parts):
        b.call('create_project',name=name,format='java_block')
        for tex in ('smooth','carved'):texture(b,tex,TEXTURES/f'cloud_jade_{tex}.png')
        for i,(n,lo,hi,t) in enumerate(parts):cuboid(b,f'{n}_{i}',lo,hi,t,uv(lo,hi))
        save_export(b,'project',MODELS/f'{name}.bbmodel')
        m=runtime_export(b,MODELS/f'{name}.json',refs);m['parent']='minecraft:block/block'
        write_json(ASSETS/f'models/block/{name}.json',m)
    for opened in (False,True):
        for part in range(4):
            name=f'cloud_jade_cabinet_{"open" if opened else "closed"}_{part}'
            parts=clipped(part,opened);project(name,parts);counts.append(len(parts))
            for facing,angle in [('north',0),('east',90),('south',180),('west',270)]:
                variants[f'facing={facing},open={str(opened).lower()},part={part}']={'model':'xiantu:block/'+name,'y':angle}
    compact=[(n,[a[0]*.5,a[1]*.5,4+a[2]*.5],[z[0]*.5,z[1]*.5,4+z[2]*.5],t) for n,a,z,t in boxes()]
    project('cloud_jade_cabinet',compact)
    write_json(ASSETS/'models/item/cloud_jade_cabinet.json',{'parent':'xiantu:block/cloud_jade_cabinet'})
    write_json(ASSETS/'blockstates/cloud_jade_cabinet.json',{'variants':variants})
    loot=block_loot('cloud_jade_cabinet');loot['pools'][0]['conditions'].append({'condition':'minecraft:block_state_property','block':'xiantu:cloud_jade_cabinet','properties':{'part':'0'}})
    write_json(DATA/'loot_tables/blocks/cloud_jade_cabinet.json',loot)
    write_json(DATA/'recipes/cloud_jade_cabinet.json',recipe('cloud_jade_cabinet',['CSC','S S','CSC'],{'C':{'item':'xiantu:cloud_jade_carved'},'S':{'item':'xiantu:cloud_jade_smooth'}},1))
    merge_tag('mineable/pickaxe',['xiantu:cloud_jade_cabinet'])
    for lang,label in [('zh_cn','云纹玉柜'),('en_us','Cloud-Pattern Jade Cabinet')]:
        p=ASSETS/f'lang/{lang}.json';data=json.loads(p.read_text(encoding='utf-8'))
        for prefix in ('block','item','container'):data[f'{prefix}.xiantu.cloud_jade_cabinet']=label
        write_json(p,data)
    write_json(MODELS/'jade-cabinet-production.json',{'target':'Java1.20.1 Forge desktop; repeatable static furniture','preference':'near vanilla with detailed joinery, substantial size','reference':'user antique double-door cabinet','size_units':[32,32,15.5],'occupancy':[2,2,1],'slots':54,'shading':'opaque vanilla AO; no PBR','texel_density':'4px per model unit; approved64px tile reuse','models':9,'part_cubes':counts,'max_triangles_per_part':max(counts)*12,'animation':'event driven closed/open states; upper double doors swing90degrees; no interpolation','per_frame_work':'none; no BER/BEWLR/ticker','images_added':0,'sounds':'native barrel open/close, stone placement/break'})
    print('Blockbench cabinet exports complete:',counts)

if __name__=='__main__':main()
